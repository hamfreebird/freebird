use crate::vm::mir::MirInst;
use crate::vm::value::Value;

/// Stardust 代码生成器 — 将 MIR 翻译为 Stardust 源码
pub struct StardustGen {
    output: String,
    indent: usize,
}

impl StardustGen {
    pub fn new() -> Self {
        Self { output: String::new(), indent: 0 }
    }

    /// 生成 Stardust 源码
    pub fn generate(&mut self, instructions: &[MirInst]) -> String {
        self.output.clear();
        self.output.push_str("// Generated by Freebird Stardust backend\n");
        self.output.push_str("// Interleaved format: each Freebird slot = (id, value) pair\n\n");

        for inst in instructions {
            self.gen_inst(inst);
        }

        self.output.clone()
    }

    fn emit(&mut self, s: &str) {
        for _ in 0..self.indent {
            self.output.push_str("  ");
        }
        self.output.push_str(s);
        self.output.push('\n');
    }

    fn gen_inst(&mut self, inst: &MirInst) {
        match inst {
            MirInst::Push { value, .. } => {
                let v = stardust_value(value);
                self.emit(&format!("Push({v})  // push id"));
                self.emit(&format!("Push({v})  // push value"));
            }
            MirInst::Pop { .. } => {
                self.emit("Pop  // pop value");
                self.emit("Pop  // pop id");
            }
            MirInst::Dup { .. } => {
                // Dup: copy top pair → need Pick(1) Pick(0) Push(new_id) Swap
                self.emit("Pick(1)  // copy value below");
                self.emit("Pick(0)  // copy id below");
                self.emit("Push(1)  // new id placeholder");
                self.emit("Swap     // reorder");
            }
            MirInst::Roll { n } => {
                if *n == 0 {
                    return;
                }
                let slots = n.abs() as usize * 2; // each position = 2 Stardust slots
                if *n > 0 {
                    // roll(+n): move pair at position n*2 to top
                    // Use multiple ShiftL to bring the pair up
                    self.emit(&format!("// roll({n}) — move pair at depth {n} to top"));
                    for _ in 0..slots {
                        self.emit("ShiftL");
                    }
                } else {
                    // roll(-n): move top pair to position n
                    self.emit(&format!("// roll({n}) — move top pair to depth {}", -n));
                    for _ in 0..slots {
                        self.emit("ShiftR");
                    }
                }
            }
            MirInst::Swap => {
                // Swap top two pairs → 4 elements rotated
                self.emit("// swap top two pairs");
                self.emit("ShiftL ShiftL ShiftL ShiftL");
                self.emit("ShiftR ShiftR");
            }
            MirInst::Pick => {
                // Pick(n): pop n (single slot), then copy pair at that position
                // Simplified: use Dup-like pattern
                self.emit("// Pick — copy pair at depth n");
                self.emit("Pop  // discard n (assumes n on stack)");
                self.emit("Pick(1) Pick(0) Push(1) Swap");
            }
            MirInst::Add { .. } => {
                // Add: pop 2 values (and their IDs) → push 1 pair
                self.emit("// Add: pop 2 pairs, push 1 result");
                self.emit("Pop Pop  // discard rhs pair");
                self.emit("Swap Pop Pop Swap"); // discard lhs pair, keep result position
                self.emit("Add");
                self.emit("Push(1)  // new id");
                self.emit("Swap");
            }
            MirInst::Sub { .. } => { self.emit("// Sub"); self.emit_binary_op("Sub"); }
            MirInst::Mul { .. } => { self.emit("// Mul"); self.emit_binary_op("Mul"); }
            MirInst::Div { .. } => { self.emit("// Div"); self.emit_binary_op("Div"); }
            MirInst::Mod { .. } => { self.emit("// Mod"); self.emit_binary_op("Mod"); }
            MirInst::Neg { .. } => {
                self.emit("// Neg: pop value, negate, push new id");
                self.emit("Pop  // discard id");
                self.emit("Swap Pop Swap"); // swap to bring value to top
                self.emit("Neg");
                self.emit("Push(1)  // new id");
                self.emit("Swap");
            }
            MirInst::Eq => { self.emit("// Eq"); self.emit_cmp_op("Eq"); }
            MirInst::Ne => { self.emit("// Ne"); self.emit_cmp_op("Ne"); }
            MirInst::Lt => { self.emit("// Lt"); self.emit_cmp_op("Lt"); }
            MirInst::Gt => { self.emit("// Gt"); self.emit_cmp_op("Gt"); }
            MirInst::Le => { self.emit("// Le"); self.emit_cmp_op("Le"); }
            MirInst::Ge => { self.emit("// Ge"); self.emit_cmp_op("Ge"); }
            MirInst::And => { self.emit("// And"); self.emit_binary_op("And"); }
            MirInst::Or  => { self.emit("// Or"); self.emit_binary_op("Or"); }
            MirInst::Not => {
                self.emit("// Not");
                self.emit("Pop  // discard id");
                self.emit("Not");
                self.emit("Push(1)  // new id");
                self.emit("Swap");
            }
            MirInst::Xor => { self.emit("// Xor"); self.emit_binary_op("Xor"); }
            MirInst::Mark(n) => { self.emit(&format!("// Mark({n})")); }
            MirInst::Jump(n) => { self.emit(&format!("// Jump({n}) — conditional jump")); }
            MirInst::UncondJump(n) => { self.emit(&format!("// UncondJump({n})")); }
            MirInst::Call { fn_id } => {
                self.emit(&format!("// Call({}) — n/m from CallElement", fn_id.0));
            }
            MirInst::Ret { argc } => {
                self.emit(&format!("// Ret({}) — return {} values", argc, argc));
            }
            MirInst::EnterScope => { self.emit("// EnterScope"); }
            MirInst::ExitScope => { self.emit("// ExitScope"); }
            MirInst::BindVar { name } => { self.emit(&format!("// BindVar({name})")); }
            MirInst::ReadVar { name } => { self.emit(&format!("// ReadVar({name})")); }
            MirInst::WriteVar { name } => { self.emit(&format!("// WriteVar({name})")); }
            MirInst::Ref { name, mutable } => {
                let m = if *mutable { "mut " } else { "" };
                self.emit(&format!("// Ref(&{m}{name})"));
            }
            MirInst::Deref => { self.emit("// Deref"); }
            MirInst::FieldAccess { index } => {
                self.emit(&format!("// FieldAccess({index})"));
            }
            MirInst::IndexAccess => { self.emit("// IndexAccess"); }
            MirInst::MakeEnum { variant, data_slots } => {
                self.emit(&format!("// MakeEnum(variant={variant}, data_slots={data_slots})"));
            }
            MirInst::EnumTag { .. } => { self.emit("// EnumTag"); }
            MirInst::AllocRemote => { self.emit("// AllocRemote"); }
            MirInst::FreeRemote => { self.emit("// FreeRemote"); }
            MirInst::RemotePush => { self.emit("// RemotePush"); }
            MirInst::RemotePop => { self.emit("// RemotePop"); }
            MirInst::RemoteLoad { index } => { self.emit(&format!("// RemoteLoad({index})")); }
            MirInst::RemoteStore { index } => { self.emit(&format!("// RemoteStore({index})")); }
            MirInst::RemoteLen => { self.emit("// RemoteLen"); }
            MirInst::SwitchToRemote => { self.emit("// SwitchToRemote"); }
            MirInst::SwitchToLocal => { self.emit("// SwitchToLocal"); }
            MirInst::NumOut => { self.emit("// NumOut"); }
            MirInst::NumIn => { self.emit("// NumIn"); }
            MirInst::CharOut => { self.emit("// CharOut"); }
            MirInst::CharIn => { self.emit("// CharIn"); }
            MirInst::DumpStack => { self.emit("// DumpStack"); }
            MirInst::DumpState => { self.emit("// DumpState"); }
            MirInst::Breakpoint => { self.emit("// Breakpoint"); }
            MirInst::Nop => {}
            MirInst::Comment(s) => { self.emit(&format!("// {s}")); }
        }
    }

    fn emit_binary_op(&mut self, op: &str) {
        // Binary op: pop 2 pairs, push 1 pair
        self.emit(&format!("Pop Pop  // discard rhs id,value"));
        self.emit("Swap  // bring lhs to top");
        self.emit("Pop Pop  // discard lhs id,value");
        self.emit(&format!("Swap {op}  // perform {op}"));
        self.emit("Push(1)  // new id");
        self.emit("Swap");
    }

    fn emit_cmp_op(&mut self, op: &str) {
        self.emit(&format!("Pop Pop  // discard rhs"));
        self.emit("Swap Pop Pop Swap  // discard lhs");
        self.emit(&format!("{op}  // compare"));
        self.emit("Push(1)  // new id for bool");
        self.emit("Swap");
    }
}

/// 将 Freebird Value 转为 Stardust 数值表示
fn stardust_value(v: &Value) -> String {
    match v {
        Value::I8(n) | Value::I16(n) | Value::I32(n) | Value::I64(n) |
        Value::Isize(n) | Value::U8(n) | Value::U16(n) | Value::U32(n) |
        Value::U64(n) | Value::Usize(n) => n.to_string(),
        Value::F32(f) => format!("{f}"),
        Value::F64(f) => format!("{f}"),
        Value::Bool(b) => if *b { "1".to_string() } else { "0".to_string() },
        Value::Char(c) => (*c as i64).to_string(),
        Value::Unit => "0".to_string(),
        Value::CallElement { argc } => argc.to_string(),
        _ => "0".to_string(),
    }
}

impl Default for StardustGen {
    fn default() -> Self {
        Self::new()
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::vm::value::Value;

    #[test]
    fn test_simple_arithmetic() {
        let mir = vec![
            MirInst::Push { value: Value::I64(3), ty: crate::vm::mir::TypeId::Unknown },
            MirInst::Push { value: Value::I64(5), ty: crate::vm::mir::TypeId::Unknown },
            MirInst::Add { ty: crate::vm::mir::TypeId::Unknown },
        ];
        let mut sd_gen = StardustGen::new();
        let output = sd_gen.generate(&mir);
        assert!(output.contains("Push(3)"));
        assert!(output.contains("Push(5)"));
        assert!(output.contains("Add"));
    }

    #[test]
    fn test_roll() {
        let mir = vec![MirInst::Roll { n: 2 }];
        let mut sd_gen = StardustGen::new();
        let output = sd_gen.generate(&mir);
        assert!(output.contains("roll(2)"));
    }
}
